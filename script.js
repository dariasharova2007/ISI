  var KEY = "isi-lang";
  var nodes = document.querySelectorAll("[data-i18n]");
  var buttons = document.querySelectorAll(".lang button");
  var metaDesc = document.querySelector('meta[name="description"]');

  function detect() {
    try {
      var saved = localStorage.getItem(KEY);
      if (saved && I18N[saved]) return saved;
    } catch (e) {}
    var langs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || ""];
    var first = String(langs[0] || "").toLowerCase().slice(0, 2);
    if (first === "uk") return "uk";
    if (first === "pl") return "pl";
    if (first === "en") return "en";
    return "ru";
  }

  function apply(lang) {
    var dict = I18N[lang] || I18N.ru;
    for (var i = 0; i < nodes.length; i++) {
      var k = nodes[i].getAttribute("data-i18n");
      if (dict[k] != null) nodes[i].textContent = dict[k];
    }
    document.documentElement.lang = lang;
    document.title = dict.metaTitle;
    if (metaDesc) metaDesc.setAttribute("content", dict.metaDesc);
    for (var j = 0; j < buttons.length; j++) {
      buttons[j].setAttribute("aria-pressed", buttons[j].getAttribute("data-lang") === lang ? "true" : "false");
    }
  }

  for (var b = 0; b < buttons.length; b++) {
    buttons[b].addEventListener("click", function () {
      var lang = this.getAttribute("data-lang");
      apply(lang);
      try { localStorage.setItem(KEY, lang); } catch (e) {}
    });
  }

  apply(detect());

  var y = document.getElementById("year");
  if (y) y.textContent = new Date().getFullYear();

